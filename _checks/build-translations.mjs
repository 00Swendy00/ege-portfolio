import {readFileSync,writeFileSync} from 'node:fs';
import path from 'node:path';
const root=path.resolve(import.meta.dirname,'..');
const read=file=>JSON.parse(readFileSync(path.join(import.meta.dirname,file),'utf8'));
const staticMap=read('static-translations.json'),dynamic=read('dynamic-translations.json');
const exact={...staticMap,...dynamic.exact};
const extra={
  'Burdur hava durumu':'Burdur weather',
  'TR':'TR','EN':'EN',
  'Açık / koyu tema':'Light / dark theme',
  'Burdur · Yükleniyor…':'Burdur · Loading…'
};
Object.assign(exact,extra);
for(const pattern of dynamic.patterns)new RegExp(pattern.source,pattern.flags);
const source="'use strict';\n// Generated by _checks/build-translations.mjs; edit the source catalogues.\nwindow.SiteTranslations="+JSON.stringify({exact,patterns:dynamic.patterns},null,2)+';\n';
writeFileSync(path.join(root,'i18n-catalog.js'),source);
console.log(Object.keys(exact).length+' bilingual strings, '+dynamic.patterns.length+' dynamic patterns.');
